-- ============================================================================
-- 검증 쿼리
-- ============================================================================
--
-- Seed 데이터가 올바르게 생성되었는지 확인
--

-- 조직 확인 (1개)
SELECT COUNT(*) AS organization_count FROM organizations;
-- 예상 결과: 1

-- 교대 확인 (4개)
SELECT COUNT(*) AS shift_count FROM shifts;
-- 예상 결과: 4

-- 직원 확인 (30개)
SELECT COUNT(*) AS employee_count FROM employees;
-- 예상 결과: 30

-- 사이트 필요 인원 확인 (28개 = 7일 × 4교대)
SELECT COUNT(*) AS requirement_count FROM site_requirements;
-- 예상 결과: 28

-- 요일별 필요 인원 합계 확인
SELECT
  day_of_week,
  SUM(required_count) AS total_required
FROM site_requirements
GROUP BY day_of_week
ORDER BY day_of_week;
-- 예상 결과:
--   0: 12 (일요일)
--   1: 11 (월요일, Day만 2명)
--   2: 12 (화요일)
--   3: 12 (수요일)
--   4: 12 (목요일)
--   5: 12 (금요일)
--   6: 12 (토요일)

-- 교대별 필요 인원 합계 확인
SELECT
  s.code AS shift_code,
  s.name AS shift_name,
  SUM(sr.required_count) AS total_required_per_week
FROM site_requirements sr
JOIN shifts s ON sr.shift_id = s.id
GROUP BY s.code, s.name
ORDER BY s.code;
-- 예상 결과:
--   D: 20 (6일×3명 + 1일×2명)
--   E: 21 (7일×3명)
--   N: 21 (7일×3명)
--   O: 21 (7일×3명)


